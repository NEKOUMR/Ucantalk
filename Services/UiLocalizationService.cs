        ["ja"] = BuildJapanese(),
        ["ko"] = BuildKorean(),
    };

    public static string NormalizeLanguage(string? code)
    {
        if (string.IsNullOrWhiteSpace(code))
        {
            return "zh";
        }

        return code.Trim().ToLowerInvariant() switch
        {
            "en" or "en-us" or "en-gb" => "en",
            "ja" or "ja-jp" => "ja",
            "ko" or "ko-kr" => "ko",
            _ => "zh",
        };
    }

    public static string Translate(string? languageCode, string sourceText)
    {
        var lang = NormalizeLanguage(languageCode);
        if (lang == "zh" || string.IsNullOrEmpty(sourceText))
        {
            return sourceText;
        }

        return Translations.TryGetValue(lang, out var dict) &&
               dict.TryGetValue(sourceText, out var translated)
            ? translated
            : sourceText;
    }

